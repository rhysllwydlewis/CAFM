// Generates docs/plan/12-screen-catalogue.md from mockups/screens.json so the
// catalogue always matches what tools/render.js produced.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const screens = JSON.parse(fs.readFileSync(path.join(root, 'mockups/screens.json'), 'utf8'));
const icons = JSON.parse(fs.readFileSync(path.join(root, 'icons/icons.json'), 'utf8'));

// Which feature-catalogue modules (docs/plan/02) each screen group covers.
const covers = {
  'Design system': 'Foundations (doc 11)',
  'Sign in': '§33 security, doc 06 login & demo',
  'Home & navigation': '§0 platform services, §28 dashboards, §30 notifications',
  'Helpdesk': '§2 helpdesk, §29 AI triage',
  'Work orders': '§3 reactive work orders',
  'Planned maintenance': '§4 PPM',
  'Assets & locations': '§1 locations, §5 assets',
  'Compliance & safety': '§6 compliance, §7 health, safety & risk',
  'Contractors & contracts': '§8 contractors, §9 contracts & SLAs',
  'Scheduling & workforce': '§10 scheduling, dispatch & workforce',
  'Inventory & purchasing': '§11 inventory & tools, §12 procurement',
  'Finance': '§13 finance, budgets & billing',
  'Documents': '§14 documents',
  'Space & workplace': '§15 space, §18 booking, §19 visitors, §20 moves',
  'Energy, IoT & sustainability': '§22 energy & sustainability, §26 IoT',
  'Capital, projects & real estate': '§16 capital planning, §17 projects, §27 real estate',
  'Services & operations': '§23 soft services, §24 fleet, §25 keys, §31 business continuity',
  'Sector packs': '§35 sector packs',
  'Reports & AI': '§28 reporting, §29 AI',
  'Super User administration': '§33 Super User administration, §32 integrations, doc 03',
  'Platform (vendor) admin': '§34 platform administration',
  'Mobile apps': '§21 mobile',
  'Communications': '§30 communications & engagement',
  'Marketing site (Phase 5 draft)': 'doc 07 pricing, Phase 5 marketing site',
  'Dark theme': 'Theme support (doc 11)',
};

const groups = {};
for (const s of screens) (groups[s.group] ||= []).push(s);
const img = (id) => `../../design/mockups/png/${id}.png`;
const html = (id) => `../../design/mockups/html/${id}.html`;

let md = `# 12 · Screen Catalogue

> Generated by \`design/tools/catalogue.js\` from the rendered mockups. Do not edit by hand: change the screen in \`design/mockups/screens/*.js\`, run \`npm run render\` and \`node tools/catalogue.js\` in \`design/\`.

**${screens.length} screens** (desktop 1440 px, tablet, mobile, print) plus **${icons.length} icons**. Every module in the [feature catalogue](02-feature-catalogue.md) has at least one screen. Each image links to its HTML source, which uses the same tokens and components the build will use.

These mockups are the visual target for the build. Data shown is demo data from the "Demo Estates Ltd" tenant ([doc 06](06-login-and-demo.md)). Layouts, components, colours and copy should be matched closely. Exact numbers and wording are illustrative.

## Contents

| Group | Screens | Covers |
|-------|---------|--------|
${Object.entries(groups).map(([g, l]) => `| [${g}](#${g.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')}) | ${l.length} | ${covers[g] || ''} |`).join('\n')}

`;
for (const [g, list] of Object.entries(groups)) {
  md += `## ${g}\n\n`;
  for (const s of list) md += `### ${s.title}\n\n\`${s.id}\` · ${s.viewport}${s.theme === 'dark' ? ' · dark theme' : ''} · [HTML source](${html(s.id)})\n\n[![${s.title}](${img(s.id)})](${img(s.id)})\n\n`;
}
md += `## Known gaps (to design during the build)

- Marketing homepage and product pages (Phase 5): designed once the product is named (decision D1). The pricing page draft is included above.
- Retail, commercial-property and public-sector pack screens (§35): reuse the healthcare and education patterns with their own templates.
- Second-level screens inside each module (e.g. every settings tab, every report): built from the components and patterns shown here; the owning agent adds a mockup when a new pattern is needed (see doc 13).
`;
fs.writeFileSync(path.resolve(root, '../docs/plan/12-screen-catalogue.md'), md);
console.log(`catalogue: ${screens.length} screens in ${Object.keys(groups).length} groups`);
